"""E2 - uncertainty and person-level reference points on the label files.

Adds to E1 the clustered intervals that Table `tab:en-audit` is missing, the
between-participant variance share with its own interval, and the two ceilings
that a person-level predictor would reach on each benchmark.

The fourth item of the E2 plan, the transferable nearest-training-participant
predictor, needs the OpenFace descriptors of E3a and is not computed here; the
report says so rather than leaving the row blank.

Outputs results_p4/E2_results.json and results_p4/E2_report.md.

Usage:  python p4_e2_uncertainty.py [--boot 2000] [--no-test]
"""
import argparse
import json
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import p4_labels as L  # noqa: E402
from p4_e1_harmonise import (DAISEE_SPLITS, EN_SPLITS, OUT, f3,  # noqa: E402
                             prepare_daisee, prepare_engagenet)


def one_benchmark(splits, prep, strict, n_boot, verbose=True):
    res = {}
    for split in splits:
        t0 = time.time()
        df = prep(split)
        d1, a1, b1 = L.build_pairs(df, "rec", strict=strict, distance=1)
        y = d1["y"].values.astype(float)
        rec = d1["rec"].values
        subj = d1["subj"].values

        row = {"n_clips_labelled": int(len(d1)),
               "n_recordings": int(d1["rec"].nunique()),
               "n_subjects": int(d1["subj"].nunique())}
        for space, sel in (("four_class", L.space_full), ("decisive", L.space_decisive)):
            keep = sel(d1)
            point = L.agreement(y, a1, b1, keep)
            block = {
                "point": point,
                "ci_recording_clustered":
                    L.cluster_bootstrap(y, a1, b1, keep, rec, n_boot=n_boot),
                "ci_subject_clustered":
                    L.cluster_bootstrap(y, a1, b1, keep, subj, n_boot=n_boot),
                "eta2_between_subject": L.eta2_between(y, keep, subj),
                "eta2_between_subject_ci":
                    L.eta2_bootstrap(y, keep, subj, n_boot=n_boot),
                "eta2_between_recording": L.eta2_between(y, keep, rec),
                "eta2_between_recording_ci":
                    L.eta2_bootstrap(y, keep, rec, n_boot=n_boot),
                "oracle_subject_majority": L.subject_majority_oracle(y, keep, subj),
                "oracle_recording_majority": L.subject_majority_oracle(y, keep, rec),
                "purity_subject": L.purity(y, keep, subj, thresh=0.8),
            }
            row[space] = block
            if verbose:
                c = block["ci_recording_clustered"]
                print("  %-10s %-10s a=%.4f [%.4f, %.4f] kappa=%.4f [%.4f, %.4f] "
                      "eta2_b=%.4f oracle(subj)=%.4f oracle(rec)=%.4f"
                      % (split, space, point["a"], c["a_lo"], c["a_hi"],
                         point["kappa"], c["kappa_lo"], c["kappa_hi"],
                         block["eta2_between_subject"],
                         block["oracle_subject_majority"],
                         block["oracle_recording_majority"]))
        row["seconds"] = round(time.time() - t0, 1)
        res[split] = row
    return res


def write_report(res, path):
    lines = []
    W = lines.append
    W("# E2 - uncertainty and person-level reference points")
    W("")
    W("Generated by `code/p4_e2_uncertainty.py` on "
      + time.strftime("%Y-%m-%d %H:%M") + ". Bootstrap replicates: "
      + str(res["settings"]["n_boot"]) + ", percentile intervals, clusters "
      "resampled with replacement and every clip of a drawn cluster kept. The "
      "chance baseline is recomputed inside each replicate, so the kappa "
      "interval carries the uncertainty of both terms.")
    W("")
    W("## 1. Agreement and kappa with clustered intervals")
    W("")
    W("| Benchmark | Split | Space | Pairs | a | 95% CI (recording) | 95% CI (subject) | kappa | 95% CI (recording) |")
    W("|---|---|---|---:|---:|---|---|---:|---|")
    for bench in ("DAiSEE", "EngageNet"):
        for split, row in res[bench].items():
            for space in ("four_class", "decisive"):
                b = row[space]
                p, cr, cs = b["point"], b["ci_recording_clustered"], b["ci_subject_clustered"]
                W("| %s | %s | %s | %d | %s | [%s, %s] | [%s, %s] | %s | [%s, %s] |"
                  % (bench, split, space.replace("_", "-"), p["pairs"], f3(p["a"]),
                     f3(cr["a_lo"]), f3(cr["a_hi"]), f3(cs["a_lo"]), f3(cs["a_hi"]),
                     f3(p["kappa"]), f3(cr["kappa_lo"]), f3(cr["kappa_hi"])))
    W("")
    W("## 2. Between-participant share of label variance")
    W("")
    W("| Benchmark | Split | Space | eta2 between subjects | 95% CI | eta2 between recordings | 95% CI |")
    W("|---|---|---|---:|---|---:|---|")
    for bench in ("DAiSEE", "EngageNet"):
        for split, row in res[bench].items():
            for space in ("four_class", "decisive"):
                b = row[space]
                cs, cr = b["eta2_between_subject_ci"], b["eta2_between_recording_ci"]
                W("| %s | %s | %s | %s | [%s, %s] | %s | [%s, %s] |"
                  % (bench, split, space.replace("_", "-"),
                     f3(b["eta2_between_subject"]), f3(cs["lo"]), f3(cs["hi"]),
                     f3(b["eta2_between_recording"]), f3(cr["lo"]), f3(cr["hi"])))
    W("")
    W("## 3. Person-level ceilings and participant purity")
    W("")
    W("The two oracles read the held-out labels, so they are ceilings on what a "
      "constant-per-participant or constant-per-recording predictor could reach, "
      "not predictors. The floor column is the majority class of the split.")
    W("")
    W("| Benchmark | Split | Space | Floor | Oracle, participant majority | Oracle, recording majority | Participants | At or above 80% one class |")
    W("|---|---|---|---:|---:|---:|---:|---:|")
    for bench in ("DAiSEE", "EngageNet"):
        for split, row in res[bench].items():
            for space in ("four_class", "decisive"):
                b = row[space]
                pu = b["purity_subject"]
                W("| %s | %s | %s | %s | %s | %s | %d | %d |"
                  % (bench, split, space.replace("_", "-"), f3(b["point"]["floor"]),
                     f3(b["oracle_subject_majority"]), f3(b["oracle_recording_majority"]),
                     pu["n_subjects"], pu["n_at_or_above"]))
    W("")
    W("## 4. Not computed here")
    W("")
    W("The transferable person-level predictor of the E2 plan, which assigns a "
      "held-out participant the majority label of the nearest training "
      "participant in feature space, needs the OpenFace descriptors produced by "
      "E3a. It is the fair comparator for the two oracles above and is left "
      "open until E3a runs.")
    W("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--boot", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=20260904)
    ap.add_argument("--no-test", action="store_true")
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)

    en_splits = [s for s in EN_SPLITS if not (args.no_test and s == "test")]
    print("DAiSEE:")
    daisee = one_benchmark(DAISEE_SPLITS, prepare_daisee, True, args.boot)
    print("EngageNet:")
    engagenet = one_benchmark(en_splits, prepare_engagenet, False, args.boot)

    res = {"settings": {"n_boot": args.boot, "seed": args.seed,
                        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
                        "engagenet_test_included": "test" in en_splits},
           "DAiSEE": daisee, "EngageNet": engagenet}
    with open(os.path.join(OUT, "E2_results.json"), "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=2)
    write_report(res, os.path.join(OUT, "E2_report.md"))
    print("wrote", os.path.join(OUT, "E2_results.json"))
    print("wrote", os.path.join(OUT, "E2_report.md"))


if __name__ == "__main__":
    main()
